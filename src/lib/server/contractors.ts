import type { Job } from '@/lib/types';

/**
 * Matches a job to a specific contractor trade account without loose substring collisions.
 * Prevents "Apex" from matching "Apex Roofing", "Apex Builders", or unrelated jobs.
 */
export function jobMatchesContractor(job: Job, accountName: string): boolean {
  if (!accountName || !accountName.trim()) return false;
  const accountLower = accountName.trim().toLowerCase();
  const notesLower = (job.notes || '').toLowerCase();
  const customerLower = (job.customer_name || '').trim().toLowerCase();
  const sigNameLower = (job.signature?.name || '').toLowerCase();

  // 1. Explicit VIP tag generated by portal orders/swaps: [VIP CONTRACTOR: <accountName>]
  if (notesLower.includes(`[vip contractor: ${accountLower}]`)) return true;

  // 2. Exact match on customer name
  if (customerLower === accountLower) return true;

  // 3. Bracketed tag in notes, e.g. [Apex Roofing]
  if (notesLower.includes(`[${accountLower}]`)) return true;

  // 4. Portal electronic signatures: "<accountName> (Net-30 Trade Account)" or "<accountName> (VIP 1-Tap Swap)"
  if (
    sigNameLower.startsWith(`${accountLower} (net-30`) ||
    sigNameLower.startsWith(`${accountLower} (vip`)
  ) {
    return true;
  }

  return false;
}
